//! v0.3.0: 2025 client uses 2025Patch (native DLL injection) instead of BepInEx.
//!
//! This module keeps the public interface the launcher and defender expect
//! (`verify_for_launcher` / `repair_for_launcher` / `sync_plugin_from_mirror`)
//! but operates on the 2025Patch files (`2025Patch.dll`, `Injector.exe`,
//! `2025patch.ini`) instead of the BepInEx layout. There is no BepInEx and no
//! RecNetPlugin in the 2025 client — the patch DLL does the host rewriting
//! natively.

use std::path::Path;

/// 2025Patch files that must exist next to `Recroom_Release.exe`.
const PATCH_FILES: &[&str] = &["2025Patch.dll", "Injector.exe", "2025patch.ini"];
const PATCH2026_FILES: &[&str] = &[
    "2026patch.dll",
    "Injector.exe",
    "2026patch.ini",
    "RecRoomScreen.bat",
    "RecRoomVR.bat",
];

/// Keep an existing public Tachyon voice key when setup refreshes the patch config.
/// VoiceKeyXml is an RSA public key, not the Photon Voice app id; the native patch
/// validates the XML again when it loads.
pub(crate) fn render_2025patch_ini(ns_host: &str, existing_ini: Option<&str>) -> String {
    let voice_key_xml = existing_ini
        .and_then(extract_public_voice_key)
        .unwrap_or_default();

    format!(
        "; Flux Rec 2025 patch configuration\n\
         ; Auto-generated by Flux Rec installer\n\
         \n\
         [config]\n\
         ApiHost={}\n\
         PhotonHost=\n\
         PhotonPort=0\n\
         EnableConsole=false\n\
         BlockDeadHosts=true\n\
         SuppressDuidMismatch=true\n\
         EnableTracing=false\n\
         VoiceKeyXml={}\n",
        ns_host, voice_key_xml
    )
}

/// Render the supported March 2026 patch configuration. The 2026 patch needs
/// both discovery and the common service domain; Flux Rec's discovery hostname
/// is a subdomain of the Worker service domain.
pub(crate) fn render_2026patch_ini(ns_host: &str, existing_ini: Option<&str>) -> String {
    let voice_key_xml = existing_ini
        .and_then(extract_public_voice_key)
        .unwrap_or_default();
    let host = ns_host
        .trim()
        .trim_start_matches("https://")
        .trim_start_matches("http://")
        .split('/')
        .next()
        .unwrap_or_default()
        .split(':')
        .next()
        .unwrap_or_default();
    let labels: Vec<&str> = host.split('.').filter(|label| !label.is_empty()).collect();
    let service_domain = if labels.len() >= 3 {
        labels[1..].join(".")
    } else {
        host.to_string()
    };

    format!(
        "; Flux Rec 2026 patch configuration\n\
         ; Auto-generated by Ripo Team Launcher for Rec Room 20260323.14\n\
         \n\
         [config]\n\
         ApiHost={}\n\
         ServerDomain={}\n\
         CachedServerDomain=\n\
         DisableCertificatePinning=true\n\
         AllowUnsignedImages=true\n\
         FramesPerSecond=0\n\
         EnableTracing=false\n\
         VoiceKeyXml={}\n",
        host, service_domain, voice_key_xml
    )
}

fn extract_public_voice_key(ini: &str) -> Option<&str> {
    let value = ini.lines().find_map(|line| {
        let (key, value) = line.trim().split_once('=')?;
        key.trim()
            .eq_ignore_ascii_case("VoiceKeyXml")
            .then_some(value.trim())
    })?;

    // Match the native patch's one-line public-key format and 2048-byte buffer.
    // Private RSA XML must never be copied into the shipped client config.
    (value.len() < 2048
        && value.starts_with("<RSAKeyValue>")
        && value.contains("<Modulus>")
        && value.contains("<Exponent>")
        && !value.contains("<D>")
        && !value.contains("<InverseQ>"))
    .then_some(value)
}

/// Quick 2025Patch health check for the launcher (`--play`).
/// Returns Ok when the patch can boot, Err(reason) when it needs repair.
pub fn verify_for_launcher(game_dir: &Path) -> Result<(), String> {
    let files = if crate::is_2026_install(game_dir) {
        PATCH2026_FILES
    } else {
        PATCH_FILES
    };
    for f in files {
        if !game_dir.join(f).is_file() {
            return Err(format!("missing {f}"));
        }
    }
    Ok(())
}

/// Repair a broken 2025Patch install from the launcher: re-downloads the
/// patch zip and reinstalls it in place (with rollback).
pub async fn repair_for_launcher(
    client: &reqwest::Client,
    game_dir: &Path,
    ns_host: &str,
    _photon_rt: &str,
    _photon_voice: &str,
    _photon_chat: &str,
    progress: &crate::progress::Progress,
) -> Result<(), String> {
    if crate::is_2026_install(game_dir) {
        return install_patch2026_embedded(game_dir, ns_host);
    }
    let patch_zip = crate::fetch_patch2025_zip(client, progress).await?;
    let mut backups = crate::transaction::BackupSet::new();
    // Protect the existing patch files so a failed reinstall rolls back.
    for f in PATCH_FILES {
        let _ = backups.protect(&game_dir.join(f));
    }
    let res = crate::install_patch2025(game_dir, &patch_zip, ns_host, progress);
    let _ = std::fs::remove_file(&patch_zip);
    match res {
        Ok(()) => {
            backups.commit();
            Ok(())
        }
        Err(e) => {
            backups.rollback();
            Err(e)
        }
    }
}

/// Re-syncs the patch payload embedded in this launcher before every --play.
/// The Windows release workflow builds the 2025 native patch first, then embeds
/// that exact DLL here so launcher updates deliver the current game hooks.
pub async fn sync_plugin_from_mirror(
    game_dir: &Path,
    _progress: &crate::progress::Progress,
) {
    if crate::is_2026_install(game_dir) {
        if let Err(error) = install_patch2026_embedded(
            game_dir,
            option_env!("FLUXREC_NS_HOST").unwrap_or("fluxrec-api.ripo-ripoteam.workers.dev"),
        ) {
            eprintln!("[2026Patch] sync failed: {error}");
        }
        return;
    }
    const EMBEDDED_PATCH_DLL: &[u8] = include_bytes!("../assets/2025Patch.dll");

    let dest_dll = game_dir.join("2025Patch.dll");

    // Force-write the packaged DLL so --play cannot retain an older patch build.
    match std::fs::write(&dest_dll, EMBEDDED_PATCH_DLL) {
        Ok(_) => println!("[2025Patch] synced embedded 2025Patch.dll ({} bytes)", EMBEDDED_PATCH_DLL.len()),
        Err(e) => eprintln!("[2025Patch] failed to write DLL: {}", e),
    }

    // Remove the wrapper backup if it exists (cleanup)
    let orig_dll = game_dir.join("2025Patch-orig.dll");
    if orig_dll.exists() {
        let _ = std::fs::remove_file(&orig_dll);
    }

    // 3. Ensure 2025patch.ini exists with correct ApiHost
    let ini = game_dir.join("2025patch.ini");
    if !ini.exists() {
        // ApiHost is baked in at compile time via env var, fallback to fluxrec-api.
        let ns_host = option_env!("FLUXREC_NS_HOST").unwrap_or("fluxrec-api.ripo-ripoteam.workers.dev");
        let ini_content = render_2025patch_ini(ns_host, None);
        if let Err(e) = std::fs::write(&ini, ini_content) {
            eprintln!("[2025Patch] failed to write 2025patch.ini: {}", e);
        } else {
            println!("[2025Patch] created 2025patch.ini (ApiHost={})", ns_host);
        }
    }
}

/// Install the complete, version-locked 2026 patch beside an existing
/// `20260323.14` client. The launcher never overlays these files on a 2025
/// install: the patch's own fingerprint guard remains authoritative.
pub(crate) fn install_patch2026_embedded(game_dir: &Path, ns_host: &str) -> Result<(), String> {
    const PATCH_DLL: &[u8] = include_bytes!("../assets/2026patch.dll");
    const INJECTOR: &[u8] = include_bytes!("../assets/2026-Injector.exe");
    const SCREEN_BATCH: &[u8] = include_bytes!("../assets/2026-RecRoomScreen.bat");
    const VR_BATCH: &[u8] = include_bytes!("../assets/2026-RecRoomVR.bat");

    for (name, bytes) in [
        ("2026patch.dll", PATCH_DLL),
        ("Injector.exe", INJECTOR),
        ("RecRoomScreen.bat", SCREEN_BATCH),
        ("RecRoomVR.bat", VR_BATCH),
    ] {
        std::fs::write(game_dir.join(name), bytes)
            .map_err(|error| format!("write {name}: {error}"))?;
    }
    let existing = std::fs::read_to_string(game_dir.join("2026patch.ini")).ok();
    std::fs::write(
        game_dir.join("2026patch.ini"),
        render_2026patch_ini(ns_host, existing.as_deref()),
    )
    .map_err(|error| format!("write 2026patch.ini: {error}"))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{extract_public_voice_key, render_2025patch_ini};

    const PUBLIC_KEY: &str =
        "<RSAKeyValue><Modulus>abc123</Modulus><Exponent>AQAB</Exponent></RSAKeyValue>";

    #[test]
    fn update_preserves_existing_public_voice_key() {
        let existing = format!("[config]\nVoiceKeyXml={PUBLIC_KEY}\n");
        let rendered = render_2025patch_ini("api.example.test", Some(&existing));

        assert!(rendered.contains(&format!("VoiceKeyXml={PUBLIC_KEY}\n")));
        assert!(rendered.contains("ApiHost=api.example.test\n"));
    }

    #[test]
    fn private_or_non_rsa_values_are_not_preserved() {
        let private = concat!(
            "<RSAKeyValue><Modulus>x</Modulus><Exponent>AQAB</Exponent>",
            "<D>private</D></RSAKeyValue>"
        );
        assert_eq!(
            extract_public_voice_key(&format!("VoiceKeyXml={private}")),
            None
        );
        assert_eq!(
            extract_public_voice_key("VoiceKeyXml=cfd2741f-4fab-46b3-a925-54d8bf922f0d"),
            None
        );
    }

    #[test]
    fn empty_config_keeps_voice_key_unset() {
        let rendered = render_2025patch_ini("api.example.test", None);
        assert!(rendered.contains("VoiceKeyXml=\n"));
    }

    #[test]
    fn patch2026_config_has_real_line_breaks_for_native_parser() {
        let rendered = render_2026patch_ini("ns.ripo-ripoteam.workers.dev", None);
        assert!(rendered.contains("[config]\nApiHost=ns.ripo-ripoteam.workers.dev\n"));
        assert!(rendered.contains("ServerDomain=ripo-ripoteam.workers.dev\n"));
        assert!(!rendered.contains("\\n"));
    }
}
